/* ---------------------------------------------------------------- SQL output */

function sqlLiteral(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    return value.length ? `array[${value.map(sqlLiteral).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof value === "object") return `${sqlLiteral(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

function buildSql() {
  const out = [
    "-- My Postcards: sample content",
    "-- Generated by `npm run seed:sql` from src/content/data/sample.ts. Do not edit by hand.",
    "-- Safe to run more than once: rows are upserted by slug.",
    "",
    "begin;",
    "",
  ];
  for (const { name, rows } of tables) {
    const columns = Object.keys(rows[0]);
    const updates = columns.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`);
    out.push(`-- ${name} (${rows.length})`);
    out.push(`insert into public.${name} (${columns.join(", ")}) values`);
    out.push(rows.map((row) => `  (${columns.map((c) => sqlLiteral(row[c])).join(", ")})`).join(",\n"));
    out.push(`on conflict (slug) do update set ${updates.join(", ")};`, "");
  }
  out.push("commit;", "");
  return out.join("\n");
}

/* ------------------------------------------------------------ Supabase upsert */

async function seedSupabase() {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error(
      "Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY.\n" +
        "Add both to .env.local (see .env.example), or run `npm run seed:sql` and paste the output into the SQL editor.",
    );
    process.exit(1);
  }
  const { createClient } = await import("@supabase/supabase-js");
  const supabase = createClient(url, key, { auth: { persistSession: false } });

  for (const { name, rows } of tables) {
    const { error } = await supabase.from(name).upsert(rows, { onConflict: "slug" });
    if (error) {
      console.error(`Failed on "${name}": ${error.message}`);
      if (error.code === "42P01") console.error("The table does not exist yet. Run supabase/schema.sql first.");
      process.exit(1);
    }
    console.log(`  ${name}: ${rows.length} rows upserted`);
  }
  console.log("Done.");
}

if (process.argv.includes("--sql")) {
  const file = resolve(root, "supabase", "seed.sql");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, buildSql());
  console.log(`Wrote ${file}`);
} else {
  await seedSupabase();
}
