/**
 * Seed Supabase with the sample journal (src/content/data/sample.ts).
 *
 *   npm run seed            Upserts the sample rows using the service-role key from .env.local.
 *   npm run seed:sql        Writes supabase/seed.sql instead, to paste into the SQL editor.
 *
 * Upsert only: it never deletes rows, so anything you add by hand is left alone. Running it
 * twice is safe. The service-role key bypasses Row Level Security; keep it in .env.local
 * (git-ignored) and never ship it to the browser.
 */
